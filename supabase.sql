create table if not exists public.profiles (
  id bigint primary key,
  name text not null,
  image_url text not null
);

insert into public.profiles (id, name, image_url)
values (1, 'محمد الساخي', 'mohamed-sakhi.png')
on conflict (id) do update
set name = excluded.name,
    image_url = excluded.image_url;

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  rating integer not null check (rating between 1 and 5),
  comment text not null check (char_length(comment) between 1 and 500),
  created_at timestamptz not null default now(),
  is_hidden boolean not null default false
);

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  review_id bigint not null references public.reviews(id) on delete cascade,
  reason text not null default 'بلاغ من الزائر',
  created_at timestamptz not null default now()
);

-- جدول المشرفين: أضف فيه UUID الخاص بحساب المشرف بعد إنشاء حسابه في Authentication.
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

-- دالة تتحقق من أن المستخدم الحالي مشرف.
create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admins
    where user_id = auth.uid()
  );
$$;

grant execute on function public.is_admin() to anon, authenticated;

alter table public.profiles enable row level security;
alter table public.reviews enable row level security;
alter table public.reports enable row level security;
alter table public.admins enable row level security;

-- حذف السياسات القديمة إن وجدت
 drop policy if exists "public read profile" on public.profiles;
 drop policy if exists "public read visible reviews" on public.reviews;
 drop policy if exists "public insert reviews" on public.reviews;
 drop policy if exists "public insert reports" on public.reports;
 drop policy if exists "admins read all reviews" on public.reviews;
 drop policy if exists "admins update reviews" on public.reviews;
 drop policy if exists "admins delete reviews" on public.reviews;
 drop policy if exists "admins read reports" on public.reports;
 drop policy if exists "admins update profile" on public.profiles;

-- الزوار يستطيعون قراءة الملف
create policy "public read profile"
on public.profiles
for select
to anon, authenticated
using (true);

-- الزوار يرون التعليقات غير المخفية فقط
create policy "public read visible reviews"
on public.reviews
for select
to anon, authenticated
using (is_hidden = false);

-- المشرف يرى جميع التعليقات، بما فيها المخفية
create policy "admins read all reviews"
on public.reviews
for select
to authenticated
using (public.is_admin());

-- الزوار يستطيعون إضافة تقييمات
create policy "public insert reviews"
on public.reviews
for insert
to anon, authenticated
with check (
  rating between 1 and 5
  and char_length(comment) between 1 and 500
  and is_hidden = false
);

-- المشرف يستطيع إخفاء/إظهار التعليقات
create policy "admins update reviews"
on public.reviews
for update
to authenticated
using (public.is_admin())
with check (public.is_admin());

-- المشرف يستطيع حذف التعليقات نهائيًا
create policy "admins delete reviews"
on public.reviews
for delete
to authenticated
using (public.is_admin());

-- الزوار يستطيعون إرسال بلاغ
create policy "public insert reports"
on public.reports
for insert
to anon, authenticated
with check (char_length(reason) between 1 and 300);

-- المشرف يستطيع قراءة البلاغات
create policy "admins read reports"
on public.reports
for select
to authenticated
using (public.is_admin());

-- المشرف يستطيع تعديل اسم وصورة الشخص من صفحة الإدارة
create policy "admins update profile"
on public.profiles
for update
to authenticated
using (public.is_admin())
with check (public.is_admin());

-- لا توجد صلاحية عامة لتعديل أو حذف البيانات.
